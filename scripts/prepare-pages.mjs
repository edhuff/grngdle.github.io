import { cp, readFile, rm, writeFile } from 'node:fs/promises'

const path = relative => new URL('../' + relative, import.meta.url)
const html = await readFile(path('dist/index.html'), 'utf8')

await rm(path('pages-assets/'), { recursive: true, force: true })
await cp(path('dist/pages-assets/'), path('pages-assets/'), { recursive: true })
await writeFile(
  path('index.html'),
  html.replace('<!doctype html>', '<!doctype html>\n<!-- Generated by npm run build:pages. Edit src/index.html. -->'),
)
