import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'
import { manualRoll, newGame, purchase } from '../src/game/game.ts'
import { seededWords } from '../src/game/generator.ts'
import { classicalRoute, rankCost, researchById } from '../src/game/research.ts'
import { exportSave } from '../src/game/save.ts'

const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--disable-dev-shm-usage'] })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, acceptDownloads: true })
  const faults = []
  page.on('pageerror', error => faults.push(String(error)))
  const nav = name => page.getByRole('navigation').getByRole('button', { name, exact: true })
  const roll = () => page.getByRole('button', { name: 'ROLL', exact: true })
  const text = value => page.getByText(value, { exact: true })
  const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('grngdle.save.production')))
  const heading = name => page.getByRole('heading', { name })

  await page.goto(process.argv[2] ?? 'http://localhost:5173', { waitUntil: 'networkidle' })
  await heading('Roll chamber').waitFor()
  assert.match(await page.getByRole('button', { name: 'Explore research' }).textContent(), /6,250 EP/)
  await page.waitForTimeout(700)
  assert.equal(await saved(), null)
  await roll().click()
  await page.getByRole('button', { name: 'REVEALING' }).waitFor()
  assert.equal((await saved()).rolls, 1)
  assert.equal((await saved()).recent[0].probability.denominator, '1000001')
  await page.waitForTimeout(800)
  assert.equal((await saved()).rolls, 1)

  await nav('Settings').click()
  await page.getByRole('checkbox', { name: /Sequential number reveal/ }).uncheck()
  await nav('Play').click()
  await roll().focus()
  await page.keyboard.down('Enter')
  for (let repeat = 0; repeat < 6; repeat++) await page.keyboard.down('Enter')
  await page.keyboard.up('Enter')
  assert.equal((await saved()).rolls, 2)
  await page.locator('.roll-details summary').click()
  assert(await page.locator('.roll-details .badge-card').first().isVisible())
  const yieldCost = rankCost(researchById.get('yield'), 0)
  for (let index = 0; index < 35 && BigInt((await saved()).balance) < yieldCost; index++) await roll().click()
  const beforeBuy = await saved()
  await nav('Research').click()
  await heading('Research map').waitFor()
  const nodes = page.locator('.map-node')
  assert.equal(await nodes.locator('.map-node-type').count(), await nodes.count())
  const economyNode = page.getByRole('button', { name: /^Yield Calibration/ })
  const expansionNode = page.getByRole('button', { name: /^Place Value/ })
  assert.equal(await economyNode.locator('.map-node-type').textContent(), 'Economics')
  assert.equal(await expansionNode.locator('.map-node-type').textContent(), 'Expansion')
  const borderColor = element => getComputedStyle(element).borderTopColor
  assert.notEqual(await economyNode.evaluate(borderColor), await expansionNode.evaluate(borderColor))
  const zoom = page.locator('.map-controls span')
  const initialZoom = parseInt(await zoom.textContent(), 10)
  await page.getByRole('button', { name: 'Zoom in' }).click()
  assert(parseInt(await zoom.textContent(), 10) > initialZoom)
  const canvas = page.getByLabel(/Research canvas/)
  const bbox = await canvas.boundingBox()
  const navigation = await page.locator('.app-header').boundingBox()
  assert.equal(bbox.width, 1440)
  assert.equal(bbox.y, navigation.height)
  assert.equal(bbox.y + bbox.height, 960)
  assert.equal(await page.getByRole('complementary', { name: 'Research details' }).count(), 0)
  const original = await page.locator('.map-world').getAttribute('style')
  await page.mouse.move(bbox.x + 12, bbox.y + 12)
  await page.mouse.down()
  await page.mouse.move(bbox.x + 82, bbox.y + 50, { steps: 4 })
  await page.mouse.up()
  assert.notEqual(await page.locator('.map-world').getAttribute('style'), original)
  await page.getByLabel('Jump to discipline').selectOption('5')
  await page.getByRole('button', { name: `Research · ${yieldCost} EP` }).click()
  await page.getByRole('complementary', { name: 'Research details' }).getByText('Researched', { exact: true }).waitFor()
  assert.equal((await saved()).purchases.yield, 1)
  assert.equal(BigInt((await saved()).balance), BigInt(beforeBuy.balance) - yieldCost)

  await page.getByRole('button', { name: 'Close research details' }).click()
  assert.equal(await page.getByRole('complementary', { name: 'Research details' }).count(), 0)

  await nav('Collection').click()
  await heading('Collection.').waitFor()
  await page.getByRole('button', { name: 'Highest EP', exact: true }).click()
  await text(/Exact outcome odds for this integer/).waitFor()
  await nav('Statistics').click()
  await heading('Rarity distribution').waitFor()
  await nav('Settings').click()
  const saveFile = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Export save' }).click()])
  const exportPath = await saveFile[0].path()
  await page.getByRole('button', { name: 'Reset game' }).click()
  assert.equal((await saved()).rolls, beforeBuy.rolls)
  await page.getByRole('button', { name: 'Delete progress' }).click()
  assert.equal((await saved()).rolls, 0)
  const upload = page.getByLabel('Select save file')
  await upload.setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{') })
  await text('The file is not valid JSON.').waitFor()
  await upload.setInputFiles(exportPath)
  await page.getByRole('button', { name: 'Replace save' }).click()
  await page.reload({ waitUntil: 'networkidle' })
  assert.equal((await saved()).purchases.yield, 1)
  assert.equal((await saved()).rolls, beforeBuy.rolls)
  await page.setViewportSize({ width: 390, height: 844 })
  assert(await page.evaluate(() => document.documentElement.scrollWidth === innerWidth))
  assert.equal(await page.getByTestId('roll-number').getAttribute('aria-label'), BigInt((await saved()).recent[0].expression.value).toLocaleString('en-US'))
  await nav('Research').click()
  await heading('Research map').waitFor()
  await page.getByRole('button', { name: 'Fit graph' }).click()
  await page.getByLabel('Jump to discipline').selectOption('5')
  await heading('Yield Calibration').waitFor()
  const mobileCanvas = await canvas.boundingBox()
  const mobileDetails = await page.getByRole('complementary', { name: 'Research details' }).boundingBox()
  assert.equal(mobileCanvas.y + mobileCanvas.height, 844)
  assert(mobileDetails.y > mobileCanvas.y + mobileCanvas.height / 2 - 30)
  assert(await page.evaluate(() => document.documentElement.scrollWidth === innerWidth))
  if (process.argv[3]) {
    const lab = await browser.newPage({ viewport: { width: 1440, height: 960 } })
    lab.on('pageerror', error => faults.push(String(error)))
    const word = seededWords(234)
    const route = [...classicalRoute()].filter(id => id !== 'expansion')
    let fixture = newGame(true)
    fixture.settings.animations = false
    for (let index = 0; index < 140; index++) {
      fixture = manualRoll(fixture, word)
      for (const id of route) fixture = purchase(fixture, id)
    }
    await lab.addInitScript(saved => {
      if (!localStorage.getItem('grngdle.save.lab')) localStorage.setItem('grngdle.save.lab', saved)
    }, exportSave(fixture))
    await lab.goto(process.argv[3], { waitUntil: 'networkidle' })
    await lab.getByText(/Developer lab/).waitFor()
    await lab.getByRole('button', { name: 'Explore research' }).click()
    await lab.getByRole('heading', { name: 'Beyond a Million' }).waitFor()
    const junctionPaths = await lab.locator('.edge-junction.edge-highlight').evaluateAll(paths => paths.map(path => path.getAttribute('d')))
    assert(junctionPaths.filter(path => path.includes('Q')).length >= 9)
    assert.equal(await lab.getByText(/manual rolls/, { exact: false }).count(), 0)
    await lab.getByRole('button', { name: 'Classical Review', exact: true }).click()
    const crossPaths = await lab.locator('.edge-cross').evaluateAll(paths => paths.map(path => path.getAttribute('d')))
    assert(crossPaths.some(path => path.includes('Q')))
    await lab.getByRole('button', { name: 'Fit graph' }).click()
    await lab.getByRole('button', { name: /^Beyond a Million/ }).click()
    const expansionCost = rankCost(researchById.get('expansion'), 0, true)
    await lab.getByRole('button', { name: `Research · ${expansionCost} EP` }).click()
    await lab.getByRole('button', { name: 'Fit graph' }).click()
    await lab.getByRole('button', { name: /^Expression Grammar/ }).click()
    const arithmeticCost = rankCost(researchById.get('arithmetic'), 0, true)
    await lab.getByRole('button', { name: `Research · ${arithmeticCost} EP` }).click()
    await lab.getByRole('navigation').getByRole('button', { name: 'Statistics' }).click()
    await lab.getByText('Sum or product', { exact: true }).waitFor()
    await lab.getByRole('navigation').getByRole('button', { name: 'Play' }).click()
    await lab.getByRole('button', { name: 'ROLL', exact: true }).click()
    const updatedLab = await lab.evaluate(() => JSON.parse(localStorage.getItem('grngdle.save.lab')))
    assert.equal(updatedLab.rolls, fixture.rolls + 1)
    assert.equal(updatedLab.purchases.expansion, 1)
    assert.equal(updatedLab.purchases.arithmetic, 1)
    assert.equal(await lab.evaluate(() => localStorage.getItem('grngdle.save.production')), null)
    console.log('Developer lab smoke passed: both unlock purchases, updated distribution, one manual roll, isolated save.')
  }
  assert.deepEqual(faults, [])
  console.log('Chromium smoke passed: manual click and key hold, idle, graph zoom/pan/buy, records, stats, settings, save export/import/reset/reload, mobile layout.')
} finally {
  await browser.close()
}
